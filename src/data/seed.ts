function hoursAgo(h: number) {
  return new Date(Date.now() - h * 3600_000).toISOString();
}

function line(food: FoodItem, qty: number) {
  return {
    foodId: food.id,
    name: food.name,
    price: food.price,
    qty,
    veg: food.veg,
    image: food.image,
  };
}

function buildOrder(
  id: string,
  userId: string,
  studentName: string,
  roll: string,
  items: { id: string; qty: number }[],
  status: Order["status"],
  paymentMethod: Order["paymentMethod"],
  paymentStatus: Order["paymentStatus"],
  createdAt: string,
): Order {
  const orderItems = items.map((i) => {
    const food = seedFoodItems.find((f) => f.id === i.id)!;
    return line(food, i.qty);
  });
  const subtotal = orderItems.reduce((s, i) => s + i.price * i.qty, 0);
  const tax = Math.round(subtotal * 0.05 * 100) / 100;
  return {
    id,
    userId,
    studentName,
    roll,
    items: orderItems,
    subtotal,
    tax,
    total: Math.round((subtotal + tax) * 100) / 100,
    status,
    paymentMethod,
    paymentStatus,
    createdAt,
    prepTime: Math.max(...orderItems.map((i) => seedFoodItems.find((f) => f.id === i.foodId)!.prepTime)),
  };
}

